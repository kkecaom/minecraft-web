// Driver: node tools/medoh/sculpt.js preview [outDir] [views]   - render preview PNGs of the sculpt
//         node tools/medoh/sculpt.js export                      - write src/shared_medoh_bp.js (the blueprint baked into the game)
'use strict';
const path = require('path'), fs = require('fs');
const { Vox, sh, put, loadGame, makeRenderer, writePNG, sheet, ROOT } = require('./vox');
const { buildMedoh, MEDOH_CHESTS } = require('./medoh');
const mc = loadGame(), render = makeRenderer(mc);
const cmd = process.argv[2] || 'preview';

const t0 = Date.now();
const medoh = buildMedoh(mc);
console.log('medoh: voxels', medoh.count(), 'bounds', medoh.bounds().join(','), (Date.now() - t0) + 'ms');

const VIEWS = {
  hero: { pos: [125, 45, 118], look: [-8, -12, 0], fov: 55 },
  top: { pos: [-12, 300, 0.01], look: [-12, 0, 0], ortho: 390 },
  under: { pos: [130, -150, 120], look: [-8, -8, 0], fov: 55 },
  side: { pos: [-12, -12, 300], look: [-12, -12, 0], ortho: 262 },
  front: { pos: [300, -12, 0], look: [0, -12, 0], ortho: 250 },
  rear: { pos: [-175, 85, 55], look: [-30, -5, 0], fov: 55 },
  head: { pos: [105, 8, 42], look: [62, -11, 0], fov: 50 },
  deck: { pos: [34, 22, 20], look: [-8, 6, 0], fov: 65 },
  wingtip: { pos: [40, 40, 150], look: [-5, -5, 78], fov: 55 },
  belly: { pos: [20, -75, 30], look: [-10, -22, 0], fov: 60 },
};
const SCENE_VIEWS = {
  scene: { pos: [172, 72, 46], look: [20, 160, 0], fov: 80 },
  far: { pos: [270, 150, 190], look: [0, 140, 0], fov: 55 },
  village: { pos: [70, 100, 62], look: [0, 100, 0], fov: 60 },
  perch: { pos: [60, 150, 60], look: [5, 160, 0], fov: 60 },
  side: { pos: [0, 150, 400], look: [0, 150, 0], ortho: 330 },
};
if (cmd === 'scene' || cmd === 'export') {
  const { buildScene, encodeBlueprint, DECK_Y, MX } = require('./scene');
  const t1 = Date.now(), scene = buildScene(mc, medoh);
  console.log('scene: voxels', scene.count(), (Date.now() - t1) + 'ms');
  if (cmd === 'scene') {
    const out = process.argv[3] || path.join(ROOT, 'tools', 'medoh', 'out');
    for (const n of (process.argv[4] || 'scene,far').split(',')) { const t = Date.now(); writePNG(path.join(out, 'scene_' + n + '.png'), render(scene, Object.assign({ w: 1100, h: 700, fogDist: 1400 }, SCENE_VIEWS[n]))); console.log('view', n, (Date.now() - t) + 'ms'); }
  } else {
    const bp = encodeBlueprint(scene), b64 = bp.packed.toString('base64');
    const js = '// ===== shared_medoh_bp.js : GENERATED by tools/medoh/sculpt.js export - the Divine Beast Vah Medoh diorama (raw-deflated column runs, base64) =====\n' +
      'const MEDOH_BP = { deckY: ' + DECK_Y + ', mx: ' + MX + ', raw: ' + bp.raw.length + ', chests: ' + JSON.stringify(MEDOH_CHESTS.map(p => [p[0] + MX, p[1] + DECK_Y, p[2]])) + ', bounds: ' + JSON.stringify(scene.bounds()) + ',\n  data: \'' + b64 + '\' };\n';
    fs.writeFileSync(path.join(ROOT, 'src', 'shared_medoh_bp.js'), js);
    console.log('blueprint: raw', bp.raw.length, 'packed', bp.packed.length, 'base64', b64.length, 'chunks', bp.chunks, 'palette', bp.palette);
  }
}
if (cmd === 'preview') {
  const out = process.argv[3] || path.join(ROOT, 'tools', 'medoh', 'out');
  const names = (process.argv[4] || 'hero,top,under,side').split(',');
  for (const n of names) {
    const o = Object.assign({ w: 1100, h: 700 }, VIEWS[n]);
    const t = Date.now(); writePNG(path.join(out, 'medoh_' + n + '.png'), render(medoh, o)); console.log('view', n, (Date.now() - t) + 'ms');
  }
}
module.exports = { medoh };
